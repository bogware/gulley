import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

/**
 * Gateway-contract conformance report (K6). The contract suite
 * (`contract.conformance.test.ts`) records one row per rule it exercises; this
 * module renders the rows to JSON and to the committed `docs/CONFORMANCE.md`.
 * The Markdown is deterministic (no timestamps) so CI can fail when the committed
 * report drifts from what the suite proves (`ci/conformance.sh`).
 */
export type ContractSource = 'anthropic' | 'codex' | 'both';

export interface ContractCaseResult {
  id: string;
  source: ContractSource;
  /** The rule, in the contract's own words where it has them. */
  requirement: string;
  /** Where the rule is stated. */
  reference: string;
  status: 'pass' | 'fail';
  detail?: string;
}

export interface ConformanceReport {
  gateway: 'gulley';
  version: string;
  cases: ContractCaseResult[];
}

const SOURCES: Record<ContractSource, string> = {
  anthropic: 'Anthropic — Claude Code gateway compatibility guide',
  codex: 'OpenAI — Codex gateway compatibility',
  both: 'Both',
};

export function renderConformanceMarkdown(report: ConformanceReport): string {
  const byId = [...report.cases].sort((a, b) => a.id.localeCompare(b.id));
  const passed = byId.filter((c) => c.status === 'pass').length;
  const lines: string[] = [];
  lines.push('# Gateway conformance report');
  lines.push('');
  lines.push(
    '<!-- Generated by `pnpm --filter @gulley/gateway conformance:report` from the contract suite; do not edit by hand. CI fails when this file drifts (ci/conformance.sh). -->',
  );
  lines.push('');
  lines.push(
    `Gulley executes the rules of [Anthropic's Claude Code gateway compatibility guide](https://code.claude.com/docs/en/llm-gateway-protocol) and [OpenAI's Codex gateway compatibility checklist](https://learn.chatgpt.com/docs/enterprise/gateway-compatibility) as black-box tests against the assembled gateway with mock upstreams, on every CI run. This report is regenerated per release.`,
  );
  lines.push('');
  lines.push(`**Result: ${passed} of ${byId.length} rules pass.**`);
  lines.push('');
  for (const source of ['anthropic', 'codex', 'both'] as const) {
    const rows = byId.filter((c) => c.source === source);
    if (rows.length === 0) continue;
    lines.push(`## ${SOURCES[source]}`);
    lines.push('');
    lines.push('| Rule | Requirement | Reference | Status |');
    lines.push('| --- | --- | --- | --- |');
    for (const c of rows) {
      const status =
        c.status === 'pass' ? '✅ pass' : `❌ fail${c.detail ? ` — ${escape(c.detail)}` : ''}`;
      lines.push(`| \`${c.id}\` | ${escape(c.requirement)} | ${escape(c.reference)} | ${status} |`);
    }
    lines.push('');
  }
  lines.push('## What is not covered');
  lines.push('');
  lines.push(
    '- Rules that need a real provider (token-count exactness, `anthropic-ratelimit-unified-*` values, model-specific capability rejections) are exercised by the manual live checks (`pnpm --filter @gulley/gateway live:*`), not here.',
  );
  lines.push(
    '- The Amazon Bedrock InvokeModel and Google Agent Platform *client* formats are not served: Gulley exposes the Anthropic Messages format and bridges to Bedrock itself.',
  );
  lines.push('- `/v1/messages/batches` and `/v1/files` are not proxied.');
  lines.push('');
  return lines.join('\n');
}

function escape(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

export function writeConformanceOutputs(report: ConformanceReport): void {
  const json = process.env['CONFORMANCE_REPORT'];
  const md = process.env['CONFORMANCE_MARKDOWN'];
  if (json) {
    mkdirSync(dirname(json), { recursive: true });
    writeFileSync(json, JSON.stringify(report, null, 2) + '\n');
  }
  if (md) {
    mkdirSync(dirname(md), { recursive: true });
    writeFileSync(md, renderConformanceMarkdown(report));
  }
}
